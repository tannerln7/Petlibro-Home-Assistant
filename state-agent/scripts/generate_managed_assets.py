#!/usr/bin/env python3
"""Generate authenticated managed-file bytes and hashes for the State Agent."""

from __future__ import annotations

import hashlib
import json
import re
import sys
from pathlib import Path


def emit_array(name: str, data: bytes) -> str:
    rows = []
    for offset in range(0, len(data), 12):
        rows.append("    " + ", ".join(f"0x{value:02x}" for value in data[offset:offset + 12]))
    body = ",\n".join(rows)
    return f"static const uint8_t {name}[] = {{\n{body}\n}};\n#define {name.upper()}_LEN {len(data)}U\n"


def main() -> int:
    if len(sys.argv) != 3:
        raise SystemExit("usage: generate_managed_assets.py MANAGED_DIR OUTPUT")
    managed = Path(sys.argv[1])
    output = Path(sys.argv[2])
    manifest = json.loads((managed / "manifest.json").read_text(encoding="utf-8"))
    if manifest.get("schema_version") != 1 or not isinstance(
        manifest.get("assets"), list
    ):
        raise SystemExit("invalid managed asset manifest")
    assets: list[tuple[str, bytes, dict[str, object]]] = []
    for asset in manifest["assets"]:
        if not isinstance(asset, dict):
            raise SystemExit("invalid embedded managed asset definition")
        if "symbol" not in asset:
            continue
        symbol = asset.get("symbol")
        source = asset.get("source")
        content = asset.get("content")
        if (
            not isinstance(symbol, str)
            or re.fullmatch(r"[A-Z][A-Z0-9_]*", symbol) is None
            or (isinstance(source, str) == isinstance(content, str))
        ):
            raise SystemExit("invalid embedded managed asset definition")
        if isinstance(source, str):
            if Path(source).name != source:
                raise SystemExit("invalid embedded managed asset source")
            data = (managed / source).read_bytes()
        else:
            data = content.encode("ascii")
        assets.append((symbol, data, asset))
    sections = [
        "/* Generated by scripts/generate_managed_assets.py; do not edit. */",
        "#ifndef PLAF203_GENERATED_MANAGED_ASSETS_H",
        "#define PLAF203_GENERATED_MANAGED_ASSETS_H",
        "#include <stdint.h>",
    ]
    for name, data, asset in assets:
        sections.append(emit_array(name, data))
        sections.append(
            f'#define {name}_SHA256 "{hashlib.sha256(data).hexdigest()}"'
        )
        path_symbol = asset.get("path_symbol")
        if path_symbol is not None:
            destination = asset.get("destination")
            if (
                not isinstance(path_symbol, str)
                or re.fullmatch(r"[A-Z][A-Z0-9_]*", path_symbol) is None
                or not isinstance(destination, str)
                or not destination.startswith("data/")
            ):
                raise SystemExit("invalid managed asset path symbol")
            sections.append(f'#define {path_symbol} "{destination[5:]}"')
        mode_symbol = asset.get("mode_symbol")
        if mode_symbol is not None:
            mode = asset.get("mode")
            if (
                not isinstance(mode_symbol, str)
                or re.fullmatch(r"[A-Z][A-Z0-9_]*", mode_symbol) is None
                or not isinstance(mode, str)
                or re.fullmatch(r"0[0-7]{3}", mode) is None
            ):
                raise SystemExit("invalid managed asset mode symbol")
            sections.append(f"#define {mode_symbol} {mode}")
    sections.append("#endif")
    output.write_text("\n\n".join(sections) + "\n", encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
