#!/usr/bin/env python3
"""Generate authenticated managed-file bytes and hashes for the State Agent."""

from __future__ import annotations

import hashlib
import sys
from pathlib import Path


def emit_array(name: str, data: bytes) -> str:
    rows = []
    for offset in range(0, len(data), 12):
        rows.append("    " + ", ".join(f"0x{value:02x}" for value in data[offset:offset + 12]))
    body = ",\n".join(rows)
    return f"static const uint8_t {name}[] = {{\n{body}\n}};\n#define {name.upper()}_LEN {len(data)}U\n"


def main() -> int:
    if len(sys.argv) != 3:
        raise SystemExit("usage: generate_managed_assets.py MANAGED_DIR OUTPUT")
    managed = Path(sys.argv[1])
    output = Path(sys.argv[2])
    assets = (
        ("MANAGED_PING", managed / "ping"),
        ("MANAGED_APP_START", managed / "app_start.sh"),
        ("LEGACY_APP_START", managed / "app_start.legacy.sh"),
    )
    sections = [
        "/* Generated by scripts/generate_managed_assets.py; do not edit. */",
        "#ifndef PLAF203_GENERATED_MANAGED_ASSETS_H",
        "#define PLAF203_GENERATED_MANAGED_ASSETS_H",
        "#include <stdint.h>",
    ]
    for name, path in assets:
        data = path.read_bytes()
        sections.append(emit_array(name, data))
        sections.append(
            f'#define {name}_SHA256 "{hashlib.sha256(data).hexdigest()}"'
        )
    sections.append("#endif")
    output.write_text("\n\n".join(sections) + "\n", encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
